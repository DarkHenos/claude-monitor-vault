'use strict';
const assert=require('assert/strict'),fs=require('fs'),path=require('path'),os=require('os');
const {detect,identify,commandProvider}=require('../companion/detection');
const setup=require('../companion/setup'),memory=require('../companion/memory');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'auto-companion-'));
const root=path.join(temp,'project');fs.mkdirSync(root);
try {
 const mock={window:{terminals:[],tabGroups:{activeTabGroup:{activeTab:{input:{viewType:'openai.chatgpt.sidebar'}}}}}};
 assert.deepEqual(detect(mock,root,{provider:'claude'},temp),['codex']);
 mock.window.tabGroups.activeTabGroup.activeTab=null;
 mock.window.activeTerminal={name:'Codex'};
 assert.deepEqual(detect(mock,root,{provider:'claude'},temp),['codex']);
  assert.equal(identify('my-claude-project'),null);
 assert.equal(commandProvider('echo codex'),null);
 assert.equal(commandProvider('"C:\\Program Files\\codex.exe" --model example'),'codex');
 mock.window.activeTerminal=null;
 fs.writeFileSync(path.join(root,'AGENTS.md'),'Existing project conventions.\n');
 assert.deepEqual(detect(mock,root,null,temp),['codex']);
 fs.writeFileSync(path.join(root,'CLAUDE.md'),'Existing Claude conventions.\n');
 assert.deepEqual(detect(mock,root,null,temp),['claude','codex']);
 mock.extensions={getExtension:id=>({isActive:id==='openai.chatgpt'})};
 assert.deepEqual(detect(mock,root,null,temp),['codex']);
 delete mock.extensions;
 console.log('PASS active Codex beats saved Claude; project evidence supports both');
 const plan=setup.plan(root,process.execPath,path.join(temp,'server.js'),'claude');
 assert.equal(plan.changes.length,4);
 const backup=memory.applyPlan(plan,path.join(temp,'backups'));
 const agents=fs.readFileSync(path.join(root,'AGENTS.md'),'utf8');
 assert.ok(agents.startsWith('Existing project conventions.'));
 assert.ok(agents.includes('vault_list')&&agents.includes('vault_run')&&agents.includes('Read CLAUDE.md'));
 assert.ok(fs.readFileSync(path.join(root,'.codex/config.toml'),'utf8').includes('"--access","claude"'));
  assert.equal(setup.plan(root,process.execPath,path.join(temp,'server.js'),'claude').changes.length,0);
 assert.deepEqual(detect(mock,root,null,temp),['claude','codex']);
 console.log('PASS automatic setup preserves instructions, adds memory and vault context, and is idempotent');
 const disconnect=setup.plan(root,'','', 'mcp',true);
 memory.applyPlan(disconnect,path.join(temp,'backups'));
 assert.ok(!fs.readFileSync(path.join(root,'AGENTS.md'),'utf8').includes('vault_run'));
 assert.ok(fs.readFileSync(path.join(root,'AGENTS.md'),'utf8').includes('Shared project memory'));
 console.log('PASS disconnect removes vault integration while keeping project memory');
 fs.writeFileSync(path.join(root,'AGENTS.override.md'),'Override');
 assert.throws(()=>setup.plan(root,process.execPath,'server'),/override/);
 fs.unlinkSync(path.join(root,'AGENTS.override.md'));
 const stale=setup.plan(root,process.execPath,'server');
 fs.appendFileSync(path.join(root,'AGENTS.md'),'\nConcurrent edit');
 assert.throws(()=>memory.applyPlan(stale,path.join(temp,'backups')),/changed/i);
 console.log('PASS overrides and concurrent edits block automatic overwrites');
}finally{fs.rmSync(temp,{recursive:true,force:true});}
